export function fill(template, vars, money) {
  return template.replace(/\{(\w+)\}/g, (_, k) => {
    const v = vars[k];
    if (v === undefined || v === null) return "";
    return typeof v === "number" && ["amount", "balance", "cut", "paid", "goal"].includes(k) ? money(v) : String(v);
  });
}
