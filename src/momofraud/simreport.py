"""Calibration and sanity checks for the simulated worlds.

    python -m momofraud.sim --name naive --adaptive-share 0
    python -m momofraud.sim --name adaptive --adaptive-share 1
    python -m momofraud.simreport          # writes reports/simulator.md and .json

Both worlds use the same seed, so their legitimate traffic is identical: only the
fraudsters' behaviour differs. What models catch is measured in stage 3
(momofraud.experiments, reports/behaviour.md), on the same worlds.
"""

from __future__ import annotations

import json

import pandas as pd

from momofraud.paths import REPORTS_DIR, ROOT

SIM_DIR = ROOT / "data" / "simulated"
SCORED_TYPES = ("TRANSFER", "CASH_OUT")
TRAIN_DAYS, VALIDATION_DAYS = range(0, 60), range(60, 75)  # test: days 75-89

ANCHORS = {  # published figures the legitimate traffic was calibrated against
    "Airtime purchase, mean (FCFA)": ("AIRTIME", 570),
    "Merchant payment, mean (FCFA)": ("PAYMENT", 4_073),
}


def load(name: str) -> dict[str, pd.DataFrame]:
    folder = SIM_DIR / name
    return {part: pd.read_parquet(folder / f"{part}.parquet")
            for part in ("transactions", "account_events", "accounts")}


def describe(world: dict[str, pd.DataFrame]) -> dict:
    tx, accounts = world["transactions"], world["accounts"]
    legit = tx[tx["is_fraud"] == 0]
    ok = legit[legit["status"] == "SUCCESS"]
    customers = accounts.loc[accounts["kind"] == "customer", "account"]
    days = tx["timestamp"].dt.normalize().nunique()
    fraud = tx[(tx["is_fraud"] == 1) & (tx["role"] == "victim_debit")]
    return {
        "transactions": int(len(tx)),
        "customers": int(len(customers)),
        "days": int(days),
        "legit_tx_per_customer_per_day": round(len(ok) / len(customers) / days, 2),
        "legit_failed_share": round(float((legit["status"] == "FAILED_FUNDS").mean()), 4),
        "legit_mean_amount": round(float(ok["amount"].mean())),
        "anchors": {label: {"simulated": round(float(ok.loc[ok["type"] == t, "amount"].mean())),
                            "published": value}
                    for label, (t, value) in ANCHORS.items()},
        "type_mix": ok["type"].value_counts(normalize=True).round(3).to_dict(),
        "victim_transactions": fraud.groupby(["scenario", "strategy"], observed=True).size()
        .rename("n").reset_index().to_dict("records"),
        "fraud_share_of_successful": round(float(tx.loc[tx["status"] == "SUCCESS", "is_fraud"].mean()), 5),
    }


def run() -> dict:
    return {"worlds": {name: describe(load(name)) for name in ("naive", "adaptive")}}


def to_markdown(r: dict) -> str:
    naive, adaptive = r["worlds"]["naive"], r["worlds"]["adaptive"]
    lines = [
        "# Simulator report",
        "",
        "Generated by `python -m momofraud.simreport`. Two simulated worlds with the same seed and the",
        "same legitimate traffic: one where every fraudster is naive, one where every fraudster adapts.",
        "",
        "## Legitimate traffic",
        "",
        "| | Simulated | Published reference |",
        "|---|---|---|",
        f"| Customers, days | {naive['customers']:,}, {naive['days']} | |",
        f"| Transactions | {naive['transactions']:,} | |",
        f"| Successful transactions per customer per day | {naive['legit_tx_per_customer_per_day']} | |",
        f"| Failed for insufficient funds | {naive['legit_failed_share']:.1%} | |",
    ]
    for label, v in naive["anchors"].items():
        lines.append(f"| {label} | {v['simulated']:,} | {v['published']:,} (CEMAC 2024) |")
    lines += [
        f"| All transactions, mean (FCFA) | {naive['legit_mean_amount']:,} | about 10,000 (Cameroon 2023) |",
        "",
        "The overall mean is lower than the national figure because the simulation has no businesses",
        "or bulk payments, which raise the national average. Transaction mix: "
        + ", ".join(f"{k.lower()} {v:.1%}" for k, v in naive["type_mix"].items()) + ".",
        "",
        "## Fraud",
        "",
        "| Scenario | Victim transactions (naive world) | Victim transactions (adaptive world) |",
        "|---|---|---|",
    ]
    counts = {w: {d["scenario"]: d["n"] for d in r["worlds"][w]["victim_transactions"]} for w in r["worlds"]}
    for scenario in counts["naive"]:
        in_adaptive = counts["adaptive"].get(scenario, 0)
        lines.append(f"| {scenario} | {counts['naive'][scenario]:,} | {in_adaptive:,} |")
    lines += [
        "",
        f"Fraudulent share of successful transactions: {naive['fraud_share_of_successful']:.3%} (naive), "
        f"{adaptive['fraud_share_of_successful']:.3%} (adaptive). This is deliberately higher than reality,",
        "so there is enough fraud to train and evaluate on.",
        "",
        "## What models catch",
        "",
        "See [behaviour.md](behaviour.md): stage 3 trains and tests models on these same worlds.",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    report = run()
    REPORTS_DIR.mkdir(exist_ok=True)
    (REPORTS_DIR / "simulator.json").write_text(json.dumps(report, indent=2, ensure_ascii=False, default=str))
    (REPORTS_DIR / "simulator.md").write_text(to_markdown(report), encoding="utf-8")
    print((REPORTS_DIR / "simulator.md").read_text(encoding="utf-8"))
